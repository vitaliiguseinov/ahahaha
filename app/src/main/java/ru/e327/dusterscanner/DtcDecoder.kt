object DtcDecoder {
    private val db = mapOf(
        "P0011" to "Положение распредвала A: слишком раннее опережение/система VVT",
        "P0106" to "Датчик давления во впускном коллекторе: диапазон/характеристика",
        "P0340" to "Датчик положения распредвала: неисправность цепи",
        "P0500" to "Датчик скорости автомобиля: неисправность",
        "P0520" to "Датчик/цепь давления масла двигателя",
        "P0011-77" to "P0011, дополнительный код производителя/режим диагностики",
        "P0011-78" to "P0011, дополнительный код производителя/режим диагностики",
        "U0101" to "Потеря связи с блоком управления трансмиссией"
